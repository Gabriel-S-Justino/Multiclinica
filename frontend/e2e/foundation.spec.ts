import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('login, seleção de clínica, escopo profissional e logout com backend real', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Identificação').fill('e2e@test.invalid');
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Sair', exact: true })).toBeVisible();
  const select = page.getByRole('combobox', { name: 'Selecionar clínica', exact: true });
  const option = await select.locator('option').nth(1).getAttribute('value');
  await select.selectOption(option!);
  await expect(page.getByRole('combobox',{name:'Profissional',exact:true}).getByRole('option',{name:'Profissional de teste E2E',exact:true})).toBeAttached();
  const accessibility = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  expect(accessibility.violations).toEqual([]);
  await page.getByRole('button', { name: 'Novo agendamento', exact: true }).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Telefone do contato (com código do país)').fill('+15550001234');
  await dialog.getByRole('button',{name:'Continuar com o contato'}).click();
  await dialog.getByLabel('Nome do paciente',{exact:true}).fill('Paciente sintético E2E');
  await dialog.getByRole('checkbox').check();
  await dialog.getByRole('combobox',{name:'Serviço',exact:true}).selectOption({label:'Consulta E2E'});
  await dialog.getByRole('combobox',{name:'Unidade',exact:true}).selectOption({label:'Unidade E2E'});
  const tomorrow=new Date(Date.now()+86400000).toLocaleDateString('en-CA',{timeZone:'America/Sao_Paulo'});
  await dialog.getByLabel('Data',{exact:true}).fill(tomorrow);
  await dialog.getByRole('button',{name:'Escolher horário'}).click();
  await dialog.locator('.slot').first().click();
  await expect(dialog.getByRole('heading',{name:'Revisar agendamento'})).toBeVisible();
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([]);
  await page.screenshot({path:'../.local/f4-review.png',fullPage:true});
  await dialog.getByRole('button',{name:'Confirmar agendamento',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'Agendamento confirmado.'})).toBeVisible();
  await expect(dialog.getByRole('heading',{name:'Paciente sintético E2E'})).toBeVisible();
  await dialog.getByRole('button',{name:'Fechar',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'../.local/f4-mobile.png',fullPage:true});
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([]);
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await expect(page.getByLabel('Senha', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => localStorage.length)).toBe(0);
});
